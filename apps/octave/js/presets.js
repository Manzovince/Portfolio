// Factory sounds. Written from scratch for Phase in DX7 terms; none are copies
// of a commercial ROM. o(coarse, fine, level, rates, levels, extras), ops
// listed 1 → 6. `d` in extras is detune relative to centre (-7…+7).
import { initOp, initPatch } from './dx7.js?v=202611112';

const o = (coarse, fine, ol, r, l, x = {}) => {
  const { d = 0, ...rest } = x;
  return initOp({ coarse, fine, ol, r, l: l.length === 2 ? [l[0], l[1], 0, 0] : l, det: 7 + d, ...rest });
};
const OFF = () => initOp({ ol: 0 });

function P(name, cat, alg, fb, ops, x = {}) {
  const p = initPatch(name);
  p.alg = alg; p.fb = fb; p.cat = cat;
  while (ops.length < 6) ops.push(OFF());
  p.ops = ops;
  if (x.transpose != null) p.transpose = x.transpose;
  if (x.lfo) Object.assign(p.lfo, x.lfo);
  if (x.pitch) p.pitchEnv = x.pitch;
  if (x.oks != null) p.oks = x.oks;
  return p;
}

